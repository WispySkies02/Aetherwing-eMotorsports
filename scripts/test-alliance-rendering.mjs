import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM} from 'jsdom';
const read=name=>JSON.parse(fs.readFileSync(new URL(`../src/data/${name}.json`,import.meta.url),'utf8'));
const drivers=read('drivers'),people=read('roster-profiles'),boards=read('charters');
const originals=JSON.stringify({drivers,people,boards});
const legacy={id:'starclutch-racing',name:'StarClutch Racing',shortName:'StarClutch Racing'};
const north={id:'northstar',name:'Northstar Racing',shortName:'Northstar'};
const lineup=fs.readFileSync(new URL('../src/components/DriverLineup.astro',import.meta.url),'utf8');
const script=lineup.match(/<script define:vars=[^>]+>([\s\S]*?)<\/script>/)[1];
const dom=new JSDOM('<section data-lineup><p data-lineup-intro></p><div data-lineup-filters></div><div data-lineup-program></div><div data-lineup-grid></div></section>',{url:'https://example.test/drivers/',runScripts:'outside-only'});
const w=dom.window,d=w.document;
Object.assign(w,{entries:structuredClone(drivers),people:structuredClone(people),boards:structuredClone(boards),profileSlugs:people.map(p=>p.slug),allianceRecords:[legacy],fetch:()=>new Promise(()=>{})});
w.eval(script);
const card=slug=>d.querySelector(`a[href="/drivers/${slug}/"]`).closest('article');
const apply=detail=>w.dispatchEvent(new w.CustomEvent('aetherwing:content',{detail}));
const filter=id=>d.querySelector(`[data-program="${id}"]`).click();
assert.equal(d.querySelectorAll('[data-lineup-grid] article').length,8);
assert.equal(card('matty').dataset.teamLabel,'STARCLUTCH RACING');
assert.equal(card('hailey').dataset.teamLabel,'AETHERWING + STARCLUTCH RACING');
filter('kmart');
apply({alliances:[{...legacy,name:'Sunset & Sons Racing',shortName:'Sunset & Sons'}]});
assert.equal(card('matty').dataset.teamLabel,'SUNSET & SONS');
assert.match(d.querySelector('[data-lineup-intro]').textContent,/Sunset & Sons Racing/);
assert.equal(d.querySelector('[data-program="kmart"]').getAttribute('aria-pressed'),'true','Rename does not reset the selected program');
const reassigned=structuredClone(drivers);
for(const row of reassigned)if(row.competitionId==='sunoco'&&['eazy','hailey'].includes(row.profile))row.allianceId=north.id;
apply({alliances:[legacy,north],drivers:reassigned});filter('all');
assert.equal(card('eazy').dataset.teamLabel,'STARCLUTCH RACING + NORTHSTAR');
assert.equal(card('hailey').dataset.teamLabel,'AETHERWING + STARCLUTCH RACING + NORTHSTAR');
assert.equal(d.querySelectorAll('[data-lineup-grid] article').length,8,'New organizations do not create duplicate driver cards');
filter('sunoco');assert.equal(card('eazy').dataset.teamLabel,'NORTHSTAR');
const quoted={...north,name:'Team "Echo" & Co',shortName:'Team "Echo" & Co'};
apply({alliances:[legacy,quoted]});
assert.equal(card('eazy').dataset.teamLabel,'TEAM "ECHO" & CO');
assert.equal(card('eazy').attributes.length,[...card('eazy').attributes].filter(a=>!a.name.includes('echo')).length,'Quotes do not create extra attributes');
const unassigned=structuredClone(drivers);unassigned.find(row=>row.id==='eazy-sunoco').allianceId='';
apply({alliances:[legacy],drivers:unassigned});assert.equal(card('eazy').dataset.teamLabel,'ALLIANCE','An explicit blank link never resolves to legacy StarClutch');
apply({alliances:[]});
assert.ok([...d.querySelectorAll('[data-lineup-grid] article')].every(c=>!c.dataset.teamLabel.includes('STARCLUTCH')),'An explicitly empty collection does not resurrect a deleted name');
filter('uarl-d1');assert.equal(d.querySelector('[data-lineup-program] strong').textContent,'3 ASSIGNED · 1 OPEN · 1 FLEXIBLE ENTRY');
assert.deepEqual([...d.querySelectorAll('[data-lineup-grid] article')].map(c=>c.dataset.number),['28','32','46','56','62']);
dom.window.close();

// Profile text and existing assignment rows refresh when only the alliance collection changes.
const profileSource=fs.readFileSync(new URL('../src/pages/drivers/[slug].astro',import.meta.url),'utf8');
const profileScript=profileSource.match(/<script>([\s\S]*?)<\/script>/)[1];
const person=structuredClone(people.find(p=>p.slug==='eazy'));
const mine=structuredClone(drivers.filter(row=>row.profile==='eazy'));
const profile=new JSDOM('<section data-profile-page data-profile-slug="eazy"><span data-profile-affiliation></span><h1 data-profile-name></h1><p data-profile-identity></p><p data-profile-bio></p><div data-profile-number></div><div data-profile-assignments></div></section><script type="application/json" data-profile-alliance-seed></script>',{url:'https://example.test/drivers/eazy/',runScripts:'outside-only'});
profile.window.document.querySelector('[data-profile-alliance-seed]').textContent=JSON.stringify({alliances:[legacy],assignments:mine,person});
profile.window.eval(profileScript);
const send=detail=>profile.window.dispatchEvent(new profile.window.CustomEvent('aetherwing:content',{detail}));
const box=()=>profile.window.document.querySelector('[data-profile-assignments]');
send({drivers:mine,'roster-profiles':[person]});
assert.match(box().textContent,/STARCLUTCH RACING/);
send({alliances:[{...legacy,name:'Renamed Racing'}]});
assert.match(box().textContent,/RENAMED RACING/);
assert.equal(profile.window.document.querySelector('[data-profile-affiliation]').textContent,'RENAMED RACING DRIVER');
assert.equal(profile.window.document.querySelector('[data-profile-bio]').textContent,person.bio,'Freeform biography is not rewritten by an alliance rename');
const currentPerson={...person,allianceId:north.id};
const split=mine.map((row,index)=>({...row,allianceId:index===0?north.id:'starclutch-racing'}));
send({alliances:[legacy,north],drivers:split,'roster-profiles':[currentPerson]});
assert.equal(profile.window.document.querySelector('[data-profile-affiliation]').textContent,'NORTHSTAR RACING DRIVER');
assert.match(box().textContent,/NORTHSTAR RACING/);assert.match(box().textContent,/STARCLUTCH RACING/);
send({alliances:[]});assert.doesNotMatch(box().textContent,/STARCLUTCH|NORTHSTAR/);assert.match(box().textContent,/ALLIANCE/);
send({'roster-profiles':[{...person,allianceId:''}],alliances:[legacy]});
assert.equal(profile.window.document.querySelector('[data-profile-affiliation]').textContent,'ALLIANCE DRIVER');
send({'roster-profiles':[{...person,affiliation:'aetherwing',allianceId:''}]});
assert.equal(profile.window.document.querySelector('[data-profile-affiliation]').textContent,'AETHERWING DRIVER');
profile.window.close();
assert.equal(JSON.stringify({drivers,people,boards}),originals,'Source roster, identities, artwork and charter data remain unchanged');
assert.ok(profileSource.includes('allianceName(a,alliances)'),'Server-rendered assignment labels use the shared resolver');
console.log('PASS: named alliance card/profile labels, rename-only publications, multiple organizations, escaping, explicit removal/unassigned links, unchanged roster counts/artwork/freeform history and D1 counts.');
